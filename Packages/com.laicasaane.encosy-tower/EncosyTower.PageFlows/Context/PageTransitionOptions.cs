using System;
using EncosyTower.EnumExtensions;

namespace EncosyTower.PageFlows
{
    /// <summary>Which side of a transition a page is on.</summary>
    public enum PageTransition
    {
        /// <summary>The page shows.</summary>
        Show,

        /// <summary>The page hides.</summary>
        Hide,
    }

    /// <summary>Options that change how the show or hide of a page runs.</summary>
    [Flags]
    public enum PageTransitionOptions
    {
        /// <summary>Run the transition as the page and its transition define it.</summary>
        Default = 0,

        /// <summary>Bypass the transition; no animation and no end state.</summary>
        /// <remarks>
        /// A transition whose <see cref="IPageTransition.ForceRunShow"/> or
        /// <see cref="IPageTransition.ForceRunHide"/> is <c>true</c> still runs.
        /// </remarks>
        NoTransition = 1 << 0,

        /// <summary>Apply the end state at once.</summary>
        ZeroDuration = 1 << 1,

        /// <summary>
        /// The transition runs with zero duration when another page transitions with this page; alone, it keeps its
        /// duration.
        /// </summary>
        ZeroDurationWithOtherPage = 1 << 2,

        /// <summary>
        /// The transition runs with zero duration when no other page transitions with this page; with another page,
        /// it keeps its duration.
        /// </summary>
        ZeroDurationWithoutOtherPage = 1 << 3,
    }

    /// <summary>Extension methods of <see cref="PageTransitionOptions"/>, generated by EncosyTower.</summary>
    [EnumExtensionsFor(typeof(PageTransitionOptions))]
    public static partial class PageTransitionOptionsExtensions { }
}
